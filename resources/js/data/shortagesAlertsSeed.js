export function summarizeShortages(rows = CURRENT_SHORTAGES) {
    const openStatuses = new Set(['Open', 'Head Office Reviewing', 'Head Office Response']);
    const open = rows.filter((row) => openStatuses.has(row.status));
    const critical = open.filter((row) => row.priority === 'Critical');
    const pendingResponses = rows.filter((row) => row.status === 'Head Office Response');
    const unique = (list) => [...new Set(list)];
    const largestAlert = UPCOMING_ALERTS.reduce(
        (best, row) => (row.gap > (best?.gap ?? -1) ? row : best),
        null,
    );

    return {
        criticalCount: critical.length,
        criticalDepartments: unique(critical.map((row) => row.department)).length,
        openCount: open.length,
        openDepartments: unique(open.map((row) => row.department)).length,
        alertDays: unique(UPCOMING_ALERTS.map((row) => row.date)).length,
        largestGap: largestAlert?.gap ?? 0,
        largestGapDate: String(largestAlert?.date || '').replace(/,?\s*\d{4}$/, ''),
        pendingResponses: pendingResponses.length,
    };
}

export function summarizeRequests(requests = INITIAL_SPECIAL_REQUESTS) {
    return {
        pending: requests.filter((row) => row.status === 'Pending Approval').length,
        approved: requests.filter((row) => row.status === 'Approved').length,
        rejected: requests.filter((row) => row.status === 'Rejected').length,
    };
}

export function nextRequestId(requests) {
    const numbers = requests.map((row) => Number.parseInt(String(row.id).split('-').pop(), 10)).filter((value) => !Number.isNaN(value));
    const next = (numbers.length ? Math.max(...numbers) : 15) + 1;
    return `SR-2026-${String(next).padStart(3, '0')}`;
}
